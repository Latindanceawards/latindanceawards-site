import math
def pts(r, v):
    """Interim points (max 35): Bayesian Google rating (25) + review volume (10), same formulas as the German ranking."""
    b = (v * r + 25 * 4.32) / (v + 25)
    g = max(0.0, 25 - 17.2 * (5 - b))
    rv = 10 * min(1.0, math.log(1 + v) / math.log(251))
    return round(g + rv, 1)

